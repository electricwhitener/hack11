def main() -> None:
    f = load()
    prs = Presentation()
    prs.slide_width, prs.slide_height = W, H

    for fn in (
        s_title, s_problem, s_finding, s_method, s_challenge,
        s_routing, s_queue, s_product, s_ai, s_stack, s_honest, s_close,
    ):
        fn(prs, f)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    prs.save(OUT)
    kb = os.path.getsize(OUT) // 1024
    print(f"wrote {os.path.relpath(OUT)}  ({len(prs.slides.__iter__.__self__._sldIdLst)} slides, {kb} KB)")


