"""
Generates the submission deck from docs/facts.json.

Every number on every slide is read from that file, which is itself generated by
`npx tsx scripts/facts.ts` straight out of the computation layer. Nothing is
typed by hand, so the deck cannot claim something the product does not compute.

Run (after regenerating facts):
    cd web && npx tsx scripts/facts.ts
    cd py-service && python build_deck.py

Out: ../docs/Nightline.pptx
"""

from __future__ import annotations

import json
import os

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from pptx.util import Emu, Inches, Pt

HERE = os.path.dirname(os.path.abspath(__file__))
FACTS = os.path.join(HERE, "..", "docs", "facts.json")
SHOTS = os.path.join(HERE, "..", "docs", "shots")
OUT = os.path.join(HERE, "..", "docs", "Nightline.pptx")

# Matches the app's dark theme so the deck and the demo read as one product.
BG = RGBColor(0x0B, 0x0F, 0x14)
CARD = RGBColor(0x15, 0x1B, 0x24)
FG = RGBColor(0xF1, 0xF5, 0xF9)
MUTED = RGBColor(0x8B, 0x99, 0xA9)
GREEN = RGBColor(0x22, 0xC5, 0x5E)
RED = RGBColor(0xEF, 0x44, 0x44)
AMBER = RGBColor(0xF5, 0x9E, 0x0B)

W, H = Inches(13.333), Inches(7.5)


def load() -> dict:
    with open(FACTS, encoding="utf-8") as f:
        return json.load(f)


def blank(prs: Presentation):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    bg = s.background.fill
    bg.solid()
    bg.fore_color.rgb = BG
    return s


def text(
    slide,
    txt,
    x,
    y,
    w,
    h,
    size=18,
    color=FG,
    bold=False,
    align=PP_ALIGN.LEFT,
    spacing=1.15,
):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0

    lines = txt.split("\n") if isinstance(txt, str) else list(txt)
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.line_spacing = spacing
        run = p.add_run()
        run.text = line
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color
        run.font.name = "Segoe UI"
    return box


def card(slide, x, y, w, h, fill=CARD):
    from pptx.enum.shapes import MSO_SHAPE

    sh = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, x, y, w, h)
    sh.fill.solid()
    sh.fill.fore_color.rgb = fill
    sh.line.fill.background()
    sh.shadow.inherit = False
    sh.text_frame.text = ""
    return sh


def stat_card(slide, x, y, w, value, label, color=FG, sub=None):
    h = Inches(1.55 if sub else 1.25)
    card(slide, x, y, w, h)
    text(slide, value, x + Inches(0.25), y + Inches(0.18), w - Inches(0.5), Inches(0.6),
         size=30, color=color, bold=True)
    text(slide, label, x + Inches(0.25), y + Inches(0.78), w - Inches(0.5), Inches(0.45),
         size=12, color=MUTED)
    if sub:
        text(slide, sub, x + Inches(0.25), y + Inches(1.12), w - Inches(0.5), Inches(0.35),
             size=10, color=MUTED)


def header(slide, kicker, title):
    text(slide, kicker, Inches(0.8), Inches(0.55), Inches(11), Inches(0.3),
         size=12, color=GREEN, bold=True)
    text(slide, title, Inches(0.8), Inches(0.95), Inches(11.7), Inches(0.9),
         size=32, color=FG, bold=True)


def bullets(slide, items, x, y, w, size=15, gap=0.62):
    for i, (head, body) in enumerate(items):
        yy = y + Inches(i * gap * 1.55)
        text(slide, head, x, yy, w, Inches(0.32), size=size, color=FG, bold=True)
        text(slide, body, x, yy + Inches(0.32), w, Inches(0.55), size=size - 3, color=MUTED)


def maybe_image(slide, name, x, y, w):
    """Drops in a screenshot if one has been saved, else a labelled placeholder."""
    for ext in (".png", ".jpg", ".jpeg"):
        p = os.path.join(SHOTS, name + ext)
        if os.path.exists(p):
            slide.shapes.add_picture(p, x, y, width=w)
            return True
    h = Emu(int(w * 0.58))
    card(slide, x, y, w, h, fill=RGBColor(0x1A, 0x21, 0x2B))
    text(slide, f"[ screenshot: {name} ]", x, y + Emu(int(h / 2)) - Inches(0.15), w,
         Inches(0.3), size=12, color=MUTED, align=PP_ALIGN.CENTER)
    return False


